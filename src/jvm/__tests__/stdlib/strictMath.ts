const view = new DataView(new ArrayBuffer(8))
const toDouble = (bits: string) => {
  view.setBigInt64(0, BigInt(bits))
  return view.getFloat64(0)
}
const toBits = (value: number) => {
  view.setFloat64(0, value)
  return view.getBigInt64(0)
}
const isNaNBits = (bits: bigint) => {
  view.setBigInt64(0, bits)
  return Number.isNaN(view.getFloat64(0))
}

const nativeName = (name: string) =>
  `${name}(${['atan2', 'pow', 'hypot', 'IEEEremainder'].includes(name) ? 'DD' : 'D'})D`

/** Calls the native method the way the JVM does and returns the double it returns. */
const call = (name: string, args: number[]): number => {
  let returned = NaN
  const thread = { returnStackFrame64: (value: number) => (returned = value) }
  ;(functions as any)[nativeName(name)](thread, args)
  return returned
}

describe('StrictMath natives', () => {
  test.each(vectors)('%s matches HotSpot bit for bit (%s, %s, %s)', (name, ...rest) => {
    const args = rest.slice(0, -1).map(toDouble)
    const expected = BigInt(rest[rest.length - 1])
    const actual = toBits(call(name, args))
    // every NaN is the same value as far as Java is concerned
    expect(actual === expected || (isNaNBits(actual) && isNaNBits(expected))).toBe(true)
  })

  test('implements every native method of java.lang.StrictMath', () => {
    expect(Object.keys(functions).sort()).toEqual(
      [
        'IEEEremainder(DD)D',
        'acos(D)D',
        'asin(D)D',
        'atan(D)D',
        'atan2(DD)D',
        'cbrt(D)D',
        'cos(D)D',
        'cosh(D)D',
        'exp(D)D',
        'expm1(D)D',
        'hypot(DD)D',
        'log(D)D',
        'log10(D)D',
        'log1p(D)D',
        'pow(DD)D',
        'sin(D)D',
        'sinh(D)D',
        'sqrt(D)D',
        'tan(D)D',
        'tanh(D)D'
      ].sort()
    )
  })

  test('well-known values', () => {
    expect(call('sqrt', [2])).toBe(1.4142135623730951)
    expect(call('pow', [2, 10])).toBe(1024)
    expect(call('pow', [2, -1074])).toBe(5e-324)
    expect(call('pow', [-8, 1 / 3])).toBeNaN()
    expect(call('pow', [-2, 3])).toBe(-8)
    expect(call('hypot', [3, 4])).toBe(5)
    expect(call('cbrt', [27])).toBe(3)
    expect(call('cbrt', [-8])).toBe(-2)
    expect(call('IEEEremainder', [10, 3])).toBe(1)
    expect(call('IEEEremainder', [11, 3])).toBe(-1)
    expect(call('IEEEremainder', [5, 2])).toBe(1)
    expect(call('atan2', [1, 1])).toBe(Math.PI / 4)
    expect(call('exp', [0])).toBe(1)
    expect(call('exp', [710])).toBe(Infinity)
  })
})
